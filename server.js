function shuffle(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function pickRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function cloneObj(obj) {
  return JSON.parse(JSON.stringify(obj));
}

function sanitizeText(raw, maxLen = 200) {
  if (typeof raw !== 'string') return '';
  return raw
    .replace(/[\u0000-\u001F\u007F]/g, '')
    .replace(/[<>]/g, '')
    .trim()
    .slice(0, maxLen);
}

function sanitizeChatMessage(raw, maxLen = 500) {
  if (typeof raw !== 'string') return { valid: false, text: '', error: 'Сообщение должно быть строкой.' };
  const normalized = raw
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n')
    .replace(/[\u0000-\u0009\u000B-\u001F\u007F]/g, '')
    .replace(/[<>]/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  if (!normalized) {
    return { valid: false, text: '', error: 'Сообщение не может быть пустым.' };
  }

  const chars = Array.from(normalized);
  if (chars.length > maxLen) {
    return {
      valid: false,
      text: chars.slice(0, maxLen).join(''),
      error: `Сообщение превышает лимит в ${maxLen} символов.`
    };
  }

  return { valid: true, text: normalized, error: null };
}

function checkChatFlood(player, text, now = Date.now()) {
  if (!player.chatGuard) {
    player.chatGuard = { timestamps: [], lastText: '', lastAt: 0 };
  }
  const guard = player.chatGuard;
  if (guard.lastAt && now - guard.lastAt < 700) {
    return { ok: false, error: 'Слишком быстрая отправка. Подождите немного.' };
  }

  guard.timestamps = guard.timestamps.filter((ts) => now - ts < 10000);
  if (guard.timestamps.length >= 5) {
    return { ok: false, error: 'Защита от флуда: не более 5 сообщений за 10 секунд.' };
  }

  if (guard.lastText && guard.lastText === text && now - guard.lastAt < 12000) {
    return { ok: false, error: 'Нельзя отправлять одинаковое сообщение подряд.' };
  }

  guard.timestamps.push(now);
  guard.lastText = text;
  guard.lastAt = now;
  return { ok: true };
}

function validatePlayerName(raw) {
  const name = sanitizeText(raw, 20);
  if (name.length < 2 || name.length > 20) {
    return { valid: false, error: 'Имя должно содержать от 2 до 20 символов.' };
  }
  return { valid: true, name };
}

function generateRoomCode(existingRooms) {
  for (let attempt = 0; attempt < 200; attempt++) {
    let code = '';
    for (let i = 0; i < 4; i++) {
      code += CODE_ALPHABET[Math.floor(Math.random() * CODE_ALPHABET.length)];
    }
    if (!existingRooms.has(code)) return code;
  }
  throw new Error('Не удалось сгенерировать уникальный код комнаты.');
}

