  function clearPhaseTimer(room) {
    if (room.phaseInterval) {
      clearInterval(room.phaseInterval);
      room.phaseInterval = null;
    }
  }

  function clearAllRoomTimers(room) {
    clearPhaseTimer(room);
    if (room.hostMigrationTimer) {
      clearTimeout(room.hostMigrationTimer);
      room.hostMigrationTimer = null;
    }
    if (room.cleanupTimer) {
      clearTimeout(room.cleanupTimer);
      room.cleanupTimer = null;
    }
    for (const p of room.players) {
      if (p.offlineTimer) {
        clearTimeout(p.offlineTimer);
        p.offlineTimer = null;
      }
    }
  }

  function startPhaseTimer(room, seconds, onExpire) {
    clearPhaseTimer(room);
    room.timerTotal = seconds;
    room.timerSeconds = seconds;
    room.phaseInterval = setInterval(() => {
      if (!rooms.has(room.code)) {
        clearPhaseTimer(room);
        return;
      }
      room.timerSeconds -= 1;
      if (room.timerSeconds <= 0) {
        room.timerSeconds = 0;
        clearPhaseTimer(room);
        onExpire();
      } else {
        io.to(room.code).emit('timer:tick', {
          timerSeconds: room.timerSeconds,
          timerTotal: room.timerTotal,
          phase: room.phase
        });
      }
    }, 1000);
  }

  function scheduleRoomCleanupIfEmpty(room) {
    const anyConnected = room.players.some((p) => p.connected);
    if (anyConnected) {
      if (room.cleanupTimer) {
        clearTimeout(room.cleanupTimer);
        room.cleanupTimer = null;
      }
      return;
    }
    if (room.cleanupTimer) return;
    room.cleanupTimer = setTimeout(() => {
      const current = rooms.get(room.code);
      if (!current) return;
      const stillEmpty = !current.players.some((p) => p.connected);
      if (stillEmpty) {
        clearAllRoomTimers(current);
        rooms.delete(current.code);
      }
    }, roomCleanupMs);
  }

  function scheduleHostMigration(room, disconnectedHost) {
    if (room.hostMigrationTimer) clearTimeout(room.hostMigrationTimer);
    room.hostMigrationTimer = setTimeout(() => {
      room.hostMigrationTimer = null;
      if (!rooms.has(room.code)) return;
      if (disconnectedHost.connected || !disconnectedHost.isHost) return;

      const candidate =
        room.players.find((p) => p.connected && p.alive && p.id !== disconnectedHost.id) ||
        room.players.find((p) => p.connected && p.id !== disconnectedHost.id);

      if (candidate) {
        disconnectedHost.isHost = false;
        candidate.isHost = true;
        room.hostId = candidate.id;
        addSystemMessage(room, `Хост ${disconnectedHost.name} не в сети более 20 сек. Полномочия хоста переданы игроку ${candidate.name}.`, 'leave');
        addDiaryEntry(room, 'Передача полномочий', `Новым координатором (хостом) стал ${candidate.name}.`, 'system');
        broadcastRoom(room);
      }
    }, hostMigrationMs);
  }

