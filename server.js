  function getPublicPlayer(player, revealAll) {
    const publicTraits = {};
    let hiddenCount = 0;
    for (const key of TRAIT_KEYS) {
      const card = player.traits ? player.traits[key] : null;
      if (!card) continue;
      if (revealAll || player.exiled || card.revealed) {
        publicTraits[key] = {
          revealed: true,
          data: card.data
        };
      } else {
        hiddenCount += 1;
        publicTraits[key] = {
          revealed: false,
          data: null
        };
      }
    }

    const canRevealSpecial = Boolean(revealAll && player.specialCard);
    return {
      id: player.id,
      name: player.name,
      avatarId: player.avatarId,
      isHost: player.isHost,
      connected: player.connected,
      ready: player.ready,
      alive: player.alive,
      exiled: player.exiled,
      offlineKickReady: !player.connected && player.disconnectedAt ? (Date.now() - player.disconnectedAt >= offlineKickMs) : false,
      disconnectedAt: player.disconnectedAt || null,
      revealedThisRound: player.revealedThisRound,
      specialCardUsed: player.specialCard ? player.specialCard.used : false,
      specialCardPublic: canRevealSpecial ? player.specialCard : null,
      immunePublic: revealAll ? player.immuneThisRound : false,
      quarantinedThisRound: Boolean(player.quarantinedRound && player.quarantinedRound === player._currentRound),
      hiddenCount,
      traits: publicTraits
    };
  }

  function getPublicRoomState(room) {
    const isEnded = room.phase === 'ended';
    const game = room.game;
    let votingInfo = null;
    if (game && (room.phase === 'voting' || room.phase === 'runoff')) {
      const alivePlayers = room.players.filter((p) => p.alive);
      votingInfo = {
        isRunoff: room.phase === 'runoff',
        candidates: room.phase === 'runoff' ? game.runoffCandidates : alivePlayers.map((p) => p.id),
        votedPlayerIds: alivePlayers.filter((p) => game.votes.has(p.id)).map((p) => p.id),
        totalVoters: alivePlayers.length,
        votesCast: game.votes.size
      };
    }

    return {
      code: room.code,
      phase: room.phase,
      hostId: room.hostId,
      round: game ? game.round : 0,
      bunkerCapacity: game ? game.bunkerCapacity : computeBunkerCapacity(room.players.length),
      timerSeconds: room.timerSeconds,
      timerTotal: room.timerTotal,
      disaster: game ? game.disaster : null,
      bunker: game ? game.bunker : null,
      players: room.players.map((p) => {
        p._currentRound = game ? game.round : 0;
        return getPublicPlayer(p, isEnded);
      }),
      chat: room.chat.slice(-500),
      diary: game ? game.diary.slice(-60) : [],
      votingHistory: game ? game.votingHistory : [],
      votingInfo,
      endSummary: game && isEnded ? game.endSummary : null
    };
  }

  const MAX_VOTE_SKIPS = 3;
  const VOTE_SKIP_MARKER = '__SKIP__';

  function getPrivatePlayerState(room, player) {
    const game = room.game;
    const hasVoted = Boolean(game && game.votes && game.votes.has(player.id));
    const voteVal = hasVoted ? game.votes.get(player.id) : null;
    const skipsUsed = player.skipsUsed || 0;
    return {
      playerId: player.id,
      roomCode: room.code,
      traits: player.traits || null,
      specialCard: player.specialCard || null,
      hasVoted,
      skippedThisVote: voteVal === VOTE_SKIP_MARKER,
      votedForId: voteVal && voteVal !== VOTE_SKIP_MARKER ? voteVal : null,
      skipsUsed,
      skipsRemaining: Math.max(0, MAX_VOTE_SKIPS - skipsUsed),
      extraVotes: player.extraVotes || 0,
      immuneThisRound: Boolean(player.immuneThisRound),
      quarantinedThisRound: Boolean(game && player.quarantinedRound === game.round),
      redirectTargetId: player.redirectTargetId || null
    };
  }

  function broadcastRoom(room) {
    const publicState = getPublicRoomState(room);
    io.to(room.code).emit('room:state', publicState);
    for (const player of room.players) {
      if (player.connected && player.socketId) {
        io.to(player.socketId).emit('player:private', getPrivatePlayerState(room, player));
      }
    }
  }

