  function generateSessionData(room) {
    const disaster = cloneObj(pickRandom(DISASTERS));
    const bunker = cloneObj(pickRandom(BUNKERS));
    const playerCount = room.players.length;
    const bunkerCapacity = computeBunkerCapacity(playerCount);

    const profPool = shuffle(PROFESSIONS);
    const bioPool = shuffle(BIOLOGIES);
    const healthPool = shuffle(HEALTHS);
    const hobbyPool = shuffle(HOBBIES);
    const phobiaPool = shuffle(PHOBIAS);
    const luggagePool = shuffle(LUGGAGE);
    const characterPool = shuffle(CHARACTERS);
    const factPool = shuffle(FACTS);
    const specialPool = shuffle(SPECIAL_CARDS);

    room.players.forEach((player, idx) => {
      player.alive = true;
      player.exiled = false;
      player.revealedThisRound = false;
      player.skipsUsed = 0;
      player.extraVotes = 0;
      player.immuneThisRound = false;
      player.quarantinedRound = 0;
      player.redirectTargetId = null;
      player.traits = {
        profession: { revealed: false, data: cloneObj(profPool[idx]) },
        biology: { revealed: false, data: cloneObj(bioPool[idx]) },
        health: { revealed: false, data: cloneObj(healthPool[idx]) },
        hobby: { revealed: false, data: cloneObj(hobbyPool[idx]) },
        phobia: { revealed: false, data: cloneObj(phobiaPool[idx]) },
        luggage: { revealed: false, data: cloneObj(luggagePool[idx]) },
        character: { revealed: false, data: cloneObj(characterPool[idx]) },
        fact: { revealed: false, data: cloneObj(factPool[idx]) }
      };
      player.specialCard = {
        ...cloneObj(specialPool[idx % specialPool.length]),
        used: false
      };
    });

    room.game = {
      round: 1,
      bunkerCapacity,
      disaster,
      bunker,
      diary: [],
      votingHistory: [],
      votes: new Map(),
      runoffCandidates: [],
      revoteArmed: false,
      nextDiscussionDuration: discussionSeconds,
      usedLuggageTitles: new Set(room.players.map((p) => p.traits.luggage.data.title)),
      endSummary: null
    };
  }

  function startDiscussionPhase(room) {
    const game = room.game;
    room.phase = 'discussion';
    game.votes.clear();
    game.runoffCandidates = [];
    for (const p of room.players) {
      p.revealedThisRound = false;
    }

    const duration = game.nextDiscussionDuration || discussionSeconds;
    game.nextDiscussionDuration = discussionSeconds;

    addSystemMessage(room, `Раунд ${game.round}: началась фаза обсуждения (${duration} сек.). Раскройте одну свою характеристику.`, 'round');
    addDiaryEntry(room, `Раунд ${game.round}`, `Началось обсуждение. В живых: ${room.players.filter((p) => p.alive).length} чел.`, 'round');
    broadcastRoom(room);

    startPhaseTimer(room, duration, () => {
      if (room.phase === 'discussion') {
        startVotingPhase(room);
      }
    });
  }

  function startVotingPhase(room, runoffCandidateIds = null) {
    const game = room.game;
    game.votes.clear();
    const isRunoff = Array.isArray(runoffCandidateIds) && runoffCandidateIds.length >= 2;
    room.phase = isRunoff ? 'runoff' : 'voting';
    game.runoffCandidates = isRunoff ? [...runoffCandidateIds] : [];

    if (isRunoff) {
      const names = game.runoffCandidates
        .map((id) => room.players.find((p) => p.id === id)?.name)
        .filter(Boolean)
        .join(', ');
      addSystemMessage(room, `Ничья! Запущено повторное голосование между кандидатами: ${names} (${votingSeconds} сек.).`, 'voting');
      addDiaryEntry(room, 'Повторное голосование', `Кандидаты: ${names}.`, 'vote');
    } else {
      addSystemMessage(room, `Раунд ${game.round}: началось голосование за изгнание (${votingSeconds} сек.).`, 'voting');
      addDiaryEntry(room, 'Голосование', `Открыт приём голосов в раунде ${game.round}.`, 'vote');
    }

    broadcastRoom(room);

    startPhaseTimer(room, votingSeconds, () => {
      if (room.phase === 'voting' || room.phase === 'runoff') {
        resolveVoting(room);
      }
    });
  }

  function resolveVoting(room) {
    clearPhaseTimer(room);
    const game = room.game;
    const isRunoff = room.phase === 'runoff';
    const alivePlayers = room.players.filter((p) => p.alive);
    const candidateIds = isRunoff ? game.runoffCandidates : alivePlayers.map((p) => p.id);

    const tally = new Map();
    for (const id of candidateIds) tally.set(id, 0);

    for (const voter of alivePlayers) {
      const targetId = game.votes.get(voter.id);
      if (!targetId || !tally.has(targetId)) continue;
      const weight = 1 + (voter.extraVotes || 0);
      tally.set(targetId, tally.get(targetId) + weight);
    }

    // Consume extra votes once tallied
    for (const voter of alivePlayers) {
      voter.extraVotes = 0;
    }

    // Apply "Devil's Advocate" vote redirects
    for (const player of alivePlayers) {
      if (player.redirectTargetId && tally.has(player.id) && tally.get(player.id) > 0) {
        const target = room.players.find((p) => p.id === player.redirectTargetId && p.alive);
        if (target && tally.has(target.id)) {
          tally.set(player.id, tally.get(player.id) - 1);
          tally.set(target.id, tally.get(target.id) + 1);
          addSystemMessage(room, `Сработал эффект «Адвокат дьявола»: 1 голос против ${player.name} перенаправлен на ${target.name}.`);
        }
      }
      player.redirectTargetId = null;
    }

    const candidatesBreakdown = candidateIds.map((id) => {
      const p = room.players.find((pl) => pl.id === id);
      return {
        playerId: id,
        name: p ? p.name : 'Неизвестно',
        votes: tally.get(id) || 0
      };
    }).sort((a, b) => b.votes - a.votes);

    const maxVotes = candidatesBreakdown.length > 0 ? candidatesBreakdown[0].votes : 0;
    const leaders = maxVotes > 0 ? candidatesBreakdown.filter((c) => c.votes === maxVotes) : [];

    // Check armed revote card
    if (game.revoteArmed && !isRunoff && maxVotes > 0) {
      game.revoteArmed = false;
      game.votingHistory.push({
        id: generateId(),
        round: game.round,
        isRunoff: false,
        candidates: candidatesBreakdown,
        outcome: 'Пересмотр приговора: голосование аннулировано спецкартой',
        exiledPlayerId: null,
        exiledName: null
      });
      addSystemMessage(room, 'Сработал эффект «Пересмотр приговора» — результаты сброшены, запускается повторное голосование!');
      startVotingPhase(room, alivePlayers.map((p) => p.id));
      return;
    }

    // No votes cast against candidates (everyone skipped or didn't vote)
    if (maxVotes === 0) {
      game.votingHistory.push({
        id: generateId(),
        round: game.round,
        isRunoff,
        candidates: candidatesBreakdown,
        outcome: 'Голосов против кандидатов нет (игроки воздержались) — изгнания не произошло',
        exiledPlayerId: null,
        exiledName: null
      });
      addSystemMessage(room, 'Никто не набрал голосов на изгнание (игроки воздержались или не успели). В этом раунде все остаются.', 'voting');
      addDiaryEntry(room, 'Итоги голосования', 'Голоса против кандидатов отсутствуют, состав группы не изменился.', 'vote');
      advanceToNextRound(room);
      return;
    }

    // Tie handling
    if (leaders.length > 1) {
      const tiedNames = leaders.map((l) => l.name).join(', ');
      if (!isRunoff) {
        game.votingHistory.push({
          id: generateId(),
          round: game.round,
          isRunoff: false,
          candidates: candidatesBreakdown,
          outcome: `Ничья между: ${tiedNames}. Назначено переголосование`,
          exiledPlayerId: null,
          exiledName: null
        });
        startVotingPhase(room, leaders.map((l) => l.playerId));
        return;
      } else {
        game.votingHistory.push({
          id: generateId(),
          round: game.round,
          isRunoff: true,
          candidates: candidatesBreakdown,
          outcome: `Повторная ничья (${tiedNames}) — никто не выбывает`,
          exiledPlayerId: null,
          exiledName: null
        });
        addSystemMessage(room, `Повторное голосование также завершилось ничьей (${tiedNames}). Никто не изгнан.`);
        addDiaryEntry(room, 'Повторная ничья', `После второго тура (${tiedNames}) никто не покинул убежище.`, 'vote');
        advanceToNextRound(room);
        return;
      }
    }

    // Clear single leader
    const leader = leaders[0];
    const targetPlayer = room.players.find((p) => p.id === leader.playerId);

    if (targetPlayer && targetPlayer.immuneThisRound) {
      targetPlayer.immuneThisRound = false;
      game.votingHistory.push({
        id: generateId(),
        round: game.round,
        isRunoff,
        candidates: candidatesBreakdown,
        outcome: `${targetPlayer.name} защищён «Неприкосновенностью» — изгнание отменено`,
        exiledPlayerId: null,
        exiledName: null
      });
      addSystemMessage(room, `${targetPlayer.name} набрал(а) больше всего голосов (${leader.votes}), но сработала «Неприкосновенность»! Никто не изгнан.`);
      addDiaryEntry(room, 'Сработала защита', `${targetPlayer.name} использовал неприкосновенность и остался в бункере.`, 'special');
      advanceToNextRound(room);
      return;
    }

    // Exile player
    if (targetPlayer) {
      targetPlayer.alive = false;
      targetPlayer.exiled = true;
      for (const k of TRAIT_KEYS) {
        targetPlayer.traits[k].revealed = true;
      }

      game.votingHistory.push({
        id: generateId(),
        round: game.round,
        isRunoff,
        candidates: candidatesBreakdown,
        outcome: `Изгнан: ${targetPlayer.name} (${leader.votes} гол.)`,
        exiledPlayerId: targetPlayer.id,
        exiledName: targetPlayer.name
      });

      addSystemMessage(room, `По итогам голосования убежище покидает ${targetPlayer.name} (${leader.votes} гол.). Все его карты раскрыты.`, 'exile');
      addDiaryEntry(room, 'Изгнание', `${targetPlayer.name} изгнан из бункера и переведён в наблюдатели.`, 'exile');
    }

    // Check victory condition immediately after exile
    const remainingAlive = room.players.filter((p) => p.alive).length;
    if (remainingAlive <= game.bunkerCapacity) {
      finishGame(room);
      return;
    }

    advanceToNextRound(room);
  }

  function advanceToNextRound(room) {
    const game = room.game;
    // Clear single-round protections
    for (const p of room.players) {
      p.immuneThisRound = false;
      p.redirectTargetId = null;
    }

    game.round += 1;

    // Trigger a random event between rounds
    if (!disableRandomEvents) {
      const event = pickRandom(RANDOM_EVENTS);
      const outcomeText = event.effect(game, room);
      addSystemMessage(room, `Событие перед раундом ${game.round}: «${event.title}» — ${event.description} ${outcomeText}`, 'event');
      addDiaryEntry(room, `Событие: ${event.title}`, `${event.description} ${outcomeText}`, 'event');
    }

    startDiscussionPhase(room);
  }

  function finishGame(room) {
    clearPhaseTimer(room);
    const game = room.game;
    room.phase = 'ended';
    room.timerSeconds = 0;
    room.timerTotal = 0;

    for (const p of room.players) {
      for (const k of TRAIT_KEYS) {
        p.traits[k].revealed = true;
      }
    }

    const survivors = room.players.filter((p) => p.alive).map((p) => ({ id: p.id, name: p.name, avatarId: p.avatarId }));
    const exiled = room.players.filter((p) => !p.alive).map((p) => ({ id: p.id, name: p.name, avatarId: p.avatarId }));

    game.endSummary = {
      survivors,
      exiled,
      rounds: game.round,
      totalVotes: game.votingHistory.length
    };

    addSystemMessage(room, `Игра завершилась! ВЫЖИВАНИЕ УСПЕШНО! Выжившие: ${survivors.map((s) => s.name).join(', ')}.`, 'gameover');
    addDiaryEntry(room, 'Финал партии', `Бункер закрыл гермодвери. Выжило ${survivors.length} из ${room.players.length} участников.`, 'end');
    broadcastRoom(room);
  }

